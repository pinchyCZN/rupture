"""Struct offsets, globals and addresses on demand, for reading decomp.

    py -3.10 tools/structmap/structmap.py size     Demo_State
    py -3.10 tools/structmap/structmap.py off      Demo_State.state
    py -3.10 tools/structmap/structmap.py at       Demo_State 0x98
    py -3.10 tools/structmap/structmap.py whatsize 0x1c4
    py -3.10 tools/structmap/structmap.py dump     Demo_State
    py -3.10 tools/structmap/structmap.py flat     [TYPE]
    py -3.10 tools/structmap/structmap.py types    [SUBSTRING]
    py -3.10 tools/structmap/structmap.py const    STATE_LOGO_IN
    py -3.10 tools/structmap/structmap.py addr     g_pad[2].buttons
    py -3.10 tools/structmap/structmap.py whatis   0x0007e3c0
    py -3.10 tools/structmap/structmap.py sym      Intro
    py -3.10 tools/structmap/structmap.py check

Reads struct_map.txt, symbol_map.txt and function_map.txt on every run.
All three are generated by tools/ghidra/demo_export_maps.java and are
small enough that there is no cache to go stale. If a type you expect is
missing, the export is older than the database - re-run it.

WHY off AND addr SHOW THEIR WORKING. An offset that is merely asserted is
one you have to take on trust while staring at a disassembly. Printing
0x90 + 3*0x20 + 0x10 lets you check it against the instruction in front
of you, which is the whole point of the exercise.

whatis is the reverse direction and the one used most: an address out of
a decompiled call or a crash goes in, and the function or global holding
it comes back, with how far into it the address lands.
"""
import io
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
EXPORTS = os.path.join(ROOT, 'reverse', 'exports')


def resolve_exports():
    """Pick the export set to read, and never guess between two.

    THE EXPORTER WRITES THREE FIXED FILENAMES, AND THIS PROJECT HAS MORE
    THAN ONE PROGRAM. Four, with the depacked image - so the exports live
    one directory per program, named for it, and something has to say
    which. In order:

        DEMO_EXPORTS      a directory, read as-is. For checking a trial
                          export before it replaces the real one
        DEMO_PROGRAM      a program name -> reverse/exports/<name>
        -p NAME           the same, on the command line
        the only one      if exactly one program has been exported

    With several exported and none named, this exits listing them rather
    than reading whichever sorts first. A silently wrong map is worse
    than no map: it answers every question confidently about the wrong
    binary, and the packed and depacked images share no addresses at all
    (CLAUDE.md rule 3).
    """
    env_dir = os.environ.get('DEMO_EXPORTS')
    if env_dir:
        return env_dir

    prog = os.environ.get('DEMO_PROGRAM')
    if '-p' in sys.argv:
        i = sys.argv.index('-p')
        prog = sys.argv[i + 1]
        del sys.argv[i:i + 2]
    if prog:
        return os.path.join(EXPORTS, prog)

    if os.path.isdir(EXPORTS):
        found = sorted(d for d in os.listdir(EXPORTS)
                       if os.path.isfile(os.path.join(EXPORTS, d,
                                                      'function_map.txt')))
        if len(found) == 1:
            return os.path.join(EXPORTS, found[0])
        if len(found) > 1:
            raise SystemExit(
                '%d programs are exported and none was named:\n  %s\n'
                'pass -p NAME, or set DEMO_PROGRAM.'
                % (len(found), '\n  '.join(found)))
    return EXPORTS


EXP = resolve_exports()
F_TYPES = os.path.join(EXP, 'struct_map.txt')
F_SYMS = os.path.join(EXP, 'symbol_map.txt')
F_FUNCS = os.path.join(EXP, 'function_map.txt')

# Ghidra's own spellings, because that is what the export writes. A size
# asserted here and a size in the database that disagree is a bug in this
# table, so keep it to types whose width is fixed by the x86-32 ABI.
SCALAR = {
    'byte': 1, 'sbyte': 1, 'char': 1, 'uchar': 1, 'bool': 1,
    'undefined1': 1, 'undefined': 1,
    'word': 2, 'sword': 2, 'short': 2, 'ushort': 2, 'wchar_t': 2,
    'wchar16': 2,
    'undefined2': 2,
    'dword': 4, 'sdword': 4, 'int': 4, 'uint': 4, 'long': 4, 'ulong': 4,
    'float': 4,
    'pointer': 4, 'pointer32': 4, 'ImageBaseOffset32': 4, 'undefined4': 4,
    'qword': 8, 'sqword': 8, 'longlong': 8, 'ulonglong': 8, 'double': 8,
    'undefined8': 8,
    'longdouble': 10, 'float10': 10,
}

# Ghidra built-ins with NO FIXED WIDTH, so they cannot go in SCALAR and
# the span assertion in check() cannot apply to them - a string global's
# length is its own content. They are still legitimate types, so check()
# skips them rather than reporting them as unmapped.
VARIABLE = ('string', 'TerminatedCString', 'unicode', 'TerminatedUnicode')

TAGS = ('verified', 'inferred', 'observed', 'guess')


class Member(object):
    def __init__(self, row):
        self.name, self.type, off, count, size = row[:5]
        self.note = row[5] if len(row) > 5 else ''
        self.off = int(off, 16)
        self.size = int(size, 16)
        self.dims = ([int(x) for x in count.split('x')] if count else [])

    @property
    def n(self):
        n = 1
        for d in self.dims:
            n *= d
        return n

    @property
    def elem(self):
        """Bytes per innermost element."""
        return self.size // self.n if self.n else self.size


class Type(object):
    def __init__(self, name, kind, size, src, origin, note):
        self.name, self.kind, self.size = name, kind, size
        self.src, self.origin, self.note = src, origin, note
        self.members = []      # struct / union
        self.values = []       # enum: (name, value)


def load_types():
    types, cur = {}, None
    if not os.path.exists(F_TYPES):
        raise SystemExit('%s is missing - run '
                         'tools/ghidra/demo_export_maps.java' % F_TYPES)
    for raw in io.open(F_TYPES, encoding='ascii'):
        line = raw.rstrip('\n')
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        if line.startswith('\t'):
            p = line[1:].split(',')
            if cur is None:
                continue
            if cur.kind == 'enum' and len(p) >= 2:
                cur.values.append((p[0], int(p[1], 16)))
            elif len(p) >= 5:
                cur.members.append(Member(p))
            continue
        p = line.split(',')
        if p[0] == 'type' and len(p) >= 6:
            cur = Type(p[1], p[2], int(p[3], 16), p[4], p[5],
                       p[6] if len(p) > 6 else '')
            types[cur.name] = cur
    return types


# How the export spelled each linear address, so a lookup can echo back
# what Ghidra shows rather than a linear number nobody can find.
SPELLING = {}


def parse_addr(s):
    """A map or command-line address -> a linear int.

    Accepts `1000:025e`, `0x1bedd` and `1bedd`. Segment:offset is
    seg*16+off, which is how real mode resolves it and therefore the one
    number that can be compared and subtracted safely.
    """
    s = s.strip()
    if ':' in s:
        seg, off = s.split(':', 1)
        return int(seg, 16) * 16 + int(off, 16)
    return int(s, 16) if not s.lower().startswith('0x') else int(s, 0)


def remember(text):
    """Parse an address out of a map and keep its spelling."""
    lin = parse_addr(text)
    SPELLING.setdefault(lin, text.strip())
    return lin


def fmt_addr(lin):
    """Display form: the export's spelling, falling back to linear."""
    return SPELLING.get(lin, '%08X' % lin)


def load_syms():
    """{name: (addr, type, dims, size, src, block)} for data globals."""
    out = {}
    if not os.path.exists(F_SYMS):
        return out
    for raw in io.open(F_SYMS, encoding='ascii'):
        line = raw.strip()
        if not line or line.startswith('#'):
            continue
        p = line.split(',')
        if len(p) < 6:
            continue
        dims = [int(x) for x in p[3].split('x')] if p[3] else []
        out[p[1]] = (remember(p[0]), p[2], dims, int(p[4], 16), p[5],
                     p[6] if len(p) > 6 else '')
    return out


def load_funcs():
    """[(addr, size, name, src, block)] sorted by address."""
    out = []
    if not os.path.exists(F_FUNCS):
        return out
    for raw in io.open(F_FUNCS, encoding='ascii'):
        line = raw.strip()
        if not line or line.startswith('#'):
            continue
        p = line.split(',')
        if len(p) < 5:
            continue
        out.append((remember(p[0]), int(p[1], 16), p[2], p[3], p[4]))
    out.sort()
    return out


def constants(types):
    """{enum member name: value}, flattened across every enum."""
    out = {}
    for t in types.values():
        if t.kind == 'enum':
            for n, v in t.values:
                out[n] = v
    return out


# Genuine SDK types - Windows, OpenGL, the CRT - loaded into the
# database from Ghidra's own archives. They are not ours, so by
# CLAUDE.md rule 6.1 we never redefine them and the exporter never
# writes them to struct_map.txt, which leaves check() reporting a
# global typed with one as "in no map". Add a name here, with its
# size read from the database, when that happens.
SDK_TYPES = {
}


def base_type(name):
    """Strip pointer stars AND the space before them.

    Ghidra writes a pointer as "Demo_Effect *", so rstrip('*') alone
    leaves a trailing space and every lookup misses - which surfaced as
    check reporting a typed global's type as being in no map.
    """
    return name.replace('*', '').strip()


def is_pointer(name):
    return name.rstrip().endswith('*')


def sizeof(name, types):
    if name in SCALAR:
        return SCALAR[name]
    if name in SDK_TYPES:
        return SDK_TYPES[name]
    if is_pointer(name):
        return 4
    if name in types:
        return types[name].size
    return None


def resolve(path, types, consts):
    """Walk a dotted path with [i] indexing. -> (offset, type, steps)."""
    toks = path.split('.')
    tname, steps, off = toks[0], [], 0
    if tname not in types:
        raise SystemExit('unknown type %r' % tname)
    for tok in toks[1:]:
        m = re.match(r'^([\w()]+)((?:\[[^\]]+\])*)$', tok)
        if not m:
            raise SystemExit('cannot parse %r' % tok)
        fname = m.group(1)
        idx = re.findall(r'\[([^\]]+)\]', m.group(2))
        t = types.get(tname)
        if t is None:
            raise SystemExit('%s is not a struct, cannot take .%s'
                             % (tname, fname))
        hit = None
        for mem in t.members:
            if mem.name == fname:
                hit = mem
                break
        if hit is None:
            raise SystemExit('%s has no member %r' % (tname, fname))
        off += hit.off
        steps.append('0x%X' % hit.off)
        dims = list(hit.dims)
        for k, rawidx in enumerate(idx):
            i = consts[rawidx] if rawidx in consts else int(rawidx, 0)
            inner = hit.elem
            for d in dims[k + 1:]:
                inner *= d
            off += i * inner
            steps.append('%d*0x%X' % (i, inner))
        tname = base_type(hit.type)
    return off, tname, steps


def flatten(tname, types, prefix='', base=0, depth=0, out=None):
    if out is None:
        out = []
    t = types.get(tname)
    if t is None or depth > 6:
        return out
    for m in t.members:
        label = prefix + m.name
        if m.dims:
            label += ''.join('[%d]' % d for d in m.dims)
        out.append((base + m.off, label, m.type, m.size))
        if m.type in types and not is_pointer(m.type):
            flatten(m.type, types, label + '.', base + m.off, depth + 1, out)
    return out


def locate(tname, want, types, base=0, path='', depth=0):
    """Walk down to the deepest thing containing an offset.

    Arrays are indexed rather than reported whole: landing in the middle
    of point[12] should name point[6].vx, not leave you to divide by the
    stride yourself - that division is the error this tool exists to
    stop you making."""
    t = types.get(tname)
    if t is None or depth > 8:
        return []
    for m in t.members:
        lo, hi = base + m.off, base + m.off + m.size
        if not (lo <= want < hi):
            continue
        label = path + m.name
        if m.dims:
            rel = want - lo
            inner = m.elem
            idx = []
            for k in range(len(m.dims)):
                span = inner
                for d in m.dims[k + 1:]:
                    span *= d
                idx.append(rel // span)
                rel %= span
            label += ''.join('[%d]' % i for i in idx)
            lo = want - rel
        rows = [(lo, label, m.type, m.elem if m.dims else m.size, m.note)]
        if m.type in types and not is_pointer(m.type):
            rows += locate(m.type, want, types, lo, label + '.', depth + 1)
        return rows
    return []


# ----------------------------------------------------------------- commands

def cmd_size(a, env):
    types = env['types']
    t = types.get(a[0])
    if not t:
        raise SystemExit('unknown type %r' % a[0])
    print('%s  0x%X (%d bytes)  %s  src=%s%s'
          % (t.name, t.size, t.size, t.kind, t.src,
             '  origin=' + t.origin if t.origin else ''))
    if t.note:
        print('  %s' % t.note)


def cmd_off(a, env):
    types, consts = env['types'], env['consts']
    off, tname, steps = resolve(a[0], types, consts)
    print('%s  =  0x%X  (%d)' % (a[0], off, off))
    print('  %s' % ' + '.join(steps))
    sz = sizeof(tname, types)
    print('  type %s%s' % (tname, '  size 0x%X' % sz if sz else ''))


def cmd_at(a, env):
    types = env['types']
    want = int(a[1], 0)
    rows = locate(a[0], want, types)
    if not rows:
        raise SystemExit('0x%X is outside %s' % (want, a[0]))
    for off, label, mtype, size, note in rows:
        d = want - off
        mark = 'exact' if d == 0 else '+0x%X into it' % d
        print('  0x%04X  %-40s %-14s 0x%-6X %s'
              % (off, label, mtype, size, mark))
        if note:
            print('          %s' % note)


def cmd_whatsize(a, env):
    want = int(a[0], 0)
    hit = [t for t in env['types'].values() if t.size == want]
    if not hit:
        print('no type is 0x%X bytes' % want)
        return
    for t in sorted(hit, key=lambda x: x.name):
        print('  %-24s 0x%X  %-7s src=%s' % (t.name, t.size, t.kind, t.src))


def cmd_dump(a, env):
    t = env['types'].get(a[0])
    if not t:
        raise SystemExit('unknown type %r' % a[0])
    if t.kind == 'enum':
        for n, v in t.values:
            print('  0x%-8X %d  %s' % (v, v, n))
        return
    for off, label, mtype, size in flatten(a[0], env['types']):
        print('  0x%04X  %-40s %-16s 0x%X' % (off, label, mtype, size))


def cmd_flat(a, env):
    types = env['types']
    names = [a[0]] if a else sorted(types)
    for n in names:
        for off, label, mtype, size in flatten(n, types):
            print('%s.%s,0x%X,%s,0x%X' % (n, label, off, mtype, size))


def cmd_types(a, env):
    want = a[0].lower() if a else ''
    print('%-28s %-9s %-8s %-9s %s'
          % ('type', 'size', 'kind', 'src', 'origin'))
    print('-' * 70)
    for t in sorted(env['types'].values(), key=lambda x: x.name):
        if want and want not in t.name.lower():
            continue
        print('%-28s 0x%-7X %-8s %-9s %s'
              % (t.name, t.size, t.kind, t.src, t.origin))


def cmd_const(a, env):
    want = a[0]
    for t in sorted(env['types'].values(), key=lambda x: x.name):
        if t.kind != 'enum':
            continue
        for n, v in t.values:
            if n == want or want.lower() in n.lower():
                print('  %-32s 0x%-8X %-8d %s' % (n, v, v, t.name))


def cmd_addr(a, env):
    """A global, plus an optional path into it, as an absolute address."""
    types, consts, syms = env['types'], env['consts'], env['syms']
    path = a[0]
    sym = re.match(r'^(\w+)', path).group(1)
    if sym not in syms:
        raise SystemExit('%r is not a named global in symbol_map.txt' % sym)
    base, tname, dims, span, src, block = syms[sym]
    rest = path[len(sym):]
    idx = re.match(r'^((?:\[[^\]]+\])*)', rest).group(1)
    tail = rest[len(idx):].lstrip('.')
    elem = sizeof(base_type(tname), types) or 0
    off, steps = 0, ['0x%08X' % base]
    for rawidx in re.findall(r'\[([^\]]+)\]', idx):
        i = consts[rawidx] if rawidx in consts else int(rawidx, 0)
        off += i * elem
        steps.append('%d*0x%X' % (i, elem))
    if tail:
        o2, _t, s2 = resolve(base_type(tname) + '.' + tail, types,
                             consts)
        off += o2
        steps.extend(s2)
    print('%s  =  0x%08X' % (path, base + off))
    print('  %s' % ' + '.join(steps))
    print('  %s is %s%s spanning 0x%X in %s  (src=%s)'
          % (sym, tname, ''.join('[%d]' % d for d in dims), span, block, src))


def cmd_whatis(a, env):
    """An address -> the function or global that holds it."""
    want = parse_addr(a[0])
    hit = False
    for addr, size, name, src, block in env['funcs']:
        if addr <= want < addr + size:
            d = want - addr
            print('  function  %-40s %-11s +0x%X  (%s, %s)'
                  % (name, fmt_addr(addr), d, src, block))
            hit = True
    for name, (addr, tname, dims, span, src, block) in \
            sorted(env['syms'].items(), key=lambda kv: kv[1][0]):
        if addr <= want < addr + max(span, 1):
            d = want - addr
            print('  global    %-40s %-11s +0x%X  %s%s  (%s, %s)'
                  % (name, fmt_addr(addr), d, tname,
                     ''.join('[%d]' % x for x in dims), src, block))
            if span and tname in env['types'] and d < span:
                elem = env['types'][tname].size
                if elem:
                    rows = locate(tname, d % elem, env['types'])
                    for off, label, mtype, size, _n in rows:
                        print('              [%d].%s  (%s)'
                              % (d // elem, label, mtype))
            hit = True
    if not hit:
        print('  %s (linear %05X) is in no named function or global'
              % (a[0], want))
        print('  the maps hold only what has been named - try Ghidra')


def cmd_sym(a, env):
    want = a[0].lower()
    for name, (addr, tname, dims, span, src, block) in \
            sorted(env['syms'].items()):
        if want in name.lower():
            print('  global    %-11s %-40s %-16s 0x%-6X %s'
                  % (fmt_addr(addr), name,
                     tname + ''.join('[%d]' % d for d in dims),
                     span, src))
    for addr, size, name, src, block in env['funcs']:
        if want in name.lower():
            print('  function  %-11s %-40s %-16s 0x%-6X %s'
                  % (fmt_addr(addr), name, '', size, src))


def cmd_check(a, env):
    types, syms = env['types'], env['syms']
    bad = 0

    for t in sorted(types.values(), key=lambda x: x.name):
        if t.src not in TAGS:
            bad += 1
            print('  %-26s src=%s - set the Ghidra description to '
                  '"[verified] origin=..."' % (t.name, t.src))
        if t.kind == 'enum':
            continue
        if t.kind == 'typedef':
            continue
        if t.kind == 'union':
            over = [m for m in t.members if m.size > t.size]
            if over:
                bad += 1
                print('  %-26s union member larger than the union' % t.name)
            continue
        tot = sum(m.size for m in t.members)
        if tot != t.size:
            bad += 1
            print('  %-26s members 0x%X but SIZE 0x%X  (off by %+d)'
                  % (t.name, tot, t.size, tot - t.size))
        prev = 0
        for m in t.members:
            if m.off != prev:
                bad += 1
                print('  %-26s %s starts at 0x%X, expected 0x%X'
                      % (t.name, m.name, m.off, prev))
            prev = m.off + m.size
        for m in t.members:
            base = base_type(m.type)
            if is_pointer(m.type) or base in SCALAR or base in types:
                continue
            bad += 1
            print('  %-26s %s has type %s, which is in no map'
                  % (t.name, m.name, m.type))

    for name, (addr, tname, dims, span, src, block) in sorted(syms.items()):
        if tname == 'undefined':
            continue
        if base_type(tname) in VARIABLE:
            continue
        # A POINTER GLOBAL IS FOUR BYTES, not sizeof the pointee. Resolving
        # the pointee here made g_pObjRegistry look like a 0x8840 global
        # occupying 4 bytes.
        if is_pointer(tname):
            elem = 4
        else:
            elem = sizeof(base_type(tname), types)
        if elem is None:
            bad += 1
            print('  %-26s global type %s is in no map' % (name, tname))
            continue
        n = 1
        for d in dims:
            n *= d
        if elem * n != span:
            bad += 1
            print('  %-26s %s%s is 0x%X but the global spans 0x%X'
                  % (name, tname, ''.join('[%d]' % d for d in dims),
                     elem * n, span))

    print()
    print('%d type(s), %d global(s), %d named function(s), %d problem(s)'
          % (len(types), len(syms), len(env['funcs']), bad))
    return 1 if bad else 0


CMDS = {
    'size': (cmd_size, 1), 'off': (cmd_off, 1), 'at': (cmd_at, 2),
    'whatsize': (cmd_whatsize, 1), 'dump': (cmd_dump, 1),
    'flat': (cmd_flat, 0), 'types': (cmd_types, 0),
    'const': (cmd_const, 1), 'addr': (cmd_addr, 1),
    'whatis': (cmd_whatis, 1), 'sym': (cmd_sym, 1),
    'check': (cmd_check, 0),
}


def main():
    argv = sys.argv[1:]
    if not argv or argv[0] not in CMDS:
        print(__doc__)
        return 2
    fn, need = CMDS[argv[0]]
    if len(argv) - 1 < need:
        print('%s needs %d argument(s)' % (argv[0], need))
        return 2
    types = load_types()
    env = {'types': types, 'consts': constants(types),
           'syms': load_syms(), 'funcs': load_funcs()}
    return fn(argv[1:], env) or 0


sys.exit(main())
